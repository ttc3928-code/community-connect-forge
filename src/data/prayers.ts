/** Returns a rotating set of prayers for a given date, so the lineup is fresh each day. */
export const getDailyPrayers = (count = 3, date: Date = new Date()): GuidedPrayer[] => {
  const start = new Date(date.getFullYear(), 0, 0);
  const dayOfYear = Math.floor((date.getTime() - start.getTime()) / 86400000);
  const offset = (dayOfYear * count) % guidedPrayers.length;
  return Array.from({ length: count }, (_, i) => guidedPrayers[(offset + i) % guidedPrayers.length]);
};

/** Returns a random set of prayers, optionally avoiding the currently shown ones. */
export const getRandomPrayers = (count = 3, excludeIds: string[] = []): GuidedPrayer[] => {
  const pool = guidedPrayers.filter((p) => !excludeIds.includes(p.id));
  const source = pool.length >= count ? pool : guidedPrayers;
  const shuffled = [...source].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count);
};
